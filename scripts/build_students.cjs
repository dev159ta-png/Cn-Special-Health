function parseName(fullName) {
  let prefix = '';
  let rest = fullName.trim();
  if (rest.startsWith('เด็กชาย')) {
    prefix = 'เด็กชาย';
    rest = rest.replace('เด็กชาย', '').trim();
  } else if (rest.startsWith('เด็กหญิง')) {
    prefix = 'เด็กหญิง';
    rest = rest.replace('เด็กหญิง', '').trim();
  } else if (rest.startsWith('นางสาว')) {
    prefix = 'นางสาว';
    rest = rest.replace('นางสาว', '').trim();
  } else if (rest.startsWith('นาย')) {
    prefix = 'นาย';
    rest = rest.replace('นาย', '').trim();
  }

  const parts = rest.split(/\s+/);
  const firstName = parts[0] || '';
  const lastName = parts.slice(1).join(' ') || '';
  return { prefix, firstName, lastName };
}

function parseGradeClassroom(gradeStr, roomNum) {
  let grade = '';
  if (gradeStr.includes('ประถมศึกษาปีที่ 1')) grade = 'ป.1';
  else if (gradeStr.includes('ประถมศึกษาปีที่ 2')) grade = 'ป.2';
  else if (gradeStr.includes('ประถมศึกษาปีที่ 3')) grade = 'ป.3';
  else if (gradeStr.includes('ประถมศึกษาปีที่ 4')) grade = 'ป.4';
  else if (gradeStr.includes('ประถมศึกษาปีที่ 5')) grade = 'ป.5';
  else if (gradeStr.includes('ประถมศึกษาปีที่ 6')) grade = 'ป.6';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 1')) grade = 'ม.1';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 2')) grade = 'ม.2';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 3')) grade = 'ม.3';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 4')) grade = 'ม.4';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 5')) grade = 'ม.5';
  else if (gradeStr.includes('มัธยมศึกษาปีที่ 6')) grade = 'ม.6';
  else grade = gradeStr;

  const classroom = `${grade}/${roomNum}`;
  return { grade, classroom };
}

function parseBirthDate(beDateStr) {
  // e.g. "8/10/2561" -> d=8, m=10, y=2561 -> CE y=2018 -> "2018-10-08"
  const parts = beDateStr.split('/');
  if (parts.length === 3) {
    const d = parseInt(parts[0], 10);
    const m = parseInt(parts[1], 10);
    const beYear = parseInt(parts[2], 10);
    const ceYear = beYear > 2400 ? beYear - 543 : beYear;
    const pad = (n) => String(n).padStart(2, '0');
    return `${ceYear}-${pad(m)}-${pad(d)}`;
  }
  return beDateStr;
}

function parseAge(ageStr) {
  // e.g. "7 ปี 9 เดือน 26 วัน" -> 7
  const match = ageStr.match(/(\d+)\s*ปี/);
  if (match) return parseInt(match[1], 10);
  return 10;
}

function calcBMI(weight, height) {
  if (!height || height <= 0) return { bmi: 0, status: 'สมส่วน' };
  // height in cm -> meters
  const hMeters = height / 100;
  const bmi = Math.round((weight / (hMeters * hMeters)) * 10) / 10;
  let status = 'สมส่วน';
  if (bmi < 16) status = 'ผอมมาก';
  else if (bmi < 18.5) status = 'น้ำหนักน้อย';
  else if (bmi < 23) status = 'สมส่วน';
  else if (bmi < 25) status = 'ท้วม';
  else if (bmi < 30) status = 'อ้วน';
  else status = 'อ้วนมาก';
  return { bmi, status };
}

